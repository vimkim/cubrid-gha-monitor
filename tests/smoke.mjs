import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { strict as assert } from 'node:assert';

const require = createRequire(import.meta.url);
const playwright = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const server = spawn('python3', ['-m', 'monitor.server', '--demo', '--port', '0'], {stdio:['ignore','pipe','pipe']});
let browser;
try {
  const url = await new Promise((resolve, reject) => {
    let output = '';
    server.stdout.on('data', chunk => { output += chunk; const match = output.match(/http:\/\/127\.0\.0\.1:\d+/); if (match) resolve(match[0]); });
    server.on('error', reject);
    server.on('exit', code => reject(new Error(`server exited ${code}`)));
    setTimeout(() => reject(new Error('server startup timed out')), 10000).unref();
  });
  browser = await playwright.chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  await page.goto(url);
  await page.getByText('DEMO · 실제 GitHub 데이터가 아닌 예시입니다.').waitFor();
  await page.getByText('테스트 계획 확인').waitFor();
  const eligible = page.locator('.run').filter({hasText:'테스트 계획 확인'});
  assert.match(await eligible.innerText(), /조건부 시나리오/);
  const notStarted = page.locator('.run').filter({hasText:'medium 시작 대기'});
  assert.match(await notStarted.innerText(), /예상/);
  await page.locator('#pr-filter').fill('8559');
  const expanded = page.locator('#active .run');
  assert.equal(await expanded.count(), 1);
  await expanded.locator('summary').click();
  assert.ok(await expanded.locator('details').evaluate(el => el.open));
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'expanded details must fit the viewport');
  const jobs = expanded.locator('.jobs');
  assert.ok(await jobs.evaluate(el => el.scrollWidth > el.clientWidth), 'the jobs table must scroll horizontally');
  await jobs.evaluate(el => { el.scrollLeft = el.scrollWidth; });
  assert.ok(await jobs.evaluate(el => el.scrollLeft > 0), 'the jobs table must be scrollable');
  await page.setViewportSize({width:1440,height:1000});
  assert.match(await expanded.innerText(), /추가 단계 대기/);
  assert.match(await expanded.innerText(), /장시간 대기/);
  await page.locator('#pr-filter').fill('8601');
  assert.equal(await page.locator('#active .run').count(), 1);
  await page.reload();
  await page.getByText('테스트 계획 확인').waitFor();
  assert.equal(await page.locator('#pr-filter').inputValue(), '8601');
  await page.locator('#clear').click();
  await page.locator('#mine-filter').check();
  assert.equal(await page.locator('#active .run').count(), 4);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({path:'/tmp/cubrid-gha-monitor-smoke.png', fullPage:true});
  assert.deepEqual(errors, []);
  const fresh = await page.evaluate(async () => (await fetch('/api/snapshot')).json());
  const stale = structuredClone(fresh);
  stale.snapshot.observed_at = new Date(Date.now() - 600000).toISOString();
  await page.route('**/api/snapshot', route => route.fulfill({status:200, contentType:'application/json', body:JSON.stringify(stale)}));
  await page.reload();
  await page.getByText('관측 데이터가 오래되었습니다.', {exact:false}).waitFor();
  await page.locator('#clear').click();
  assert.match(await page.locator('#active').innerText(), /예상 불가 · 관측 데이터가 오래됨/);
  assert.doesNotMatch(await page.locator('#active').innerText(), /예상 \d/);
  await page.locator('.run').filter({hasText:'테스트 계획 확인'}).locator('summary').click();
  assert.doesNotMatch(await page.locator('#active').innerText(), /예상 \d/);
  await page.unroute('**/api/snapshot');
  const partial = structuredClone(fresh); partial.snapshot.coverage = false;
  await page.route('**/api/snapshot', route => route.fulfill({status:200, contentType:'application/json', body:JSON.stringify(partial)}));
  await page.reload();
  await page.getByText('수집 주의:', {exact:false}).waitFor();
  assert.doesNotMatch(await page.locator('#active').innerText(), /예상 \d/);
  await page.unroute('**/api/snapshot');
  const failed = structuredClone(fresh); failed.error = 'offline';
  await page.route('**/api/snapshot', route => route.fulfill({status:200, contentType:'application/json', body:JSON.stringify(failed)}));
  await page.reload();
  await page.getByText('갱신 실패.', {exact:false}).waitFor();
  assert.doesNotMatch(await page.locator('#active').innerText(), /예상 \d/);
  await page.unroute('**/api/snapshot');
  await page.route('**/api/snapshot', route => route.fulfill({status:200, contentType:'application/json', body:JSON.stringify({snapshot:null,error:'offline',loading:false})}));
  await page.reload();
  await page.getByText('GitHub 데이터를 읽지 못했습니다: offline').waitFor();
  assert.deepEqual(errors, []);
  console.log('Headless smoke passed: demo, forecasts, stale and partial data, filters, persistence, details, mobile, errors.');
} finally {
  if (browser) await browser.close();
  server.kill('SIGTERM');
}
